H("2.1.2  气象观测数据标准",3)
P("中国气象局（CMA）建立了覆盖全国的地面和高空气象观测网络。地面气象观测数据包括气压、气温、相对湿度、风向风速、降水量等要素，观测频率通常为每3小时一次（每日8个时次）。高空气象观测（探空）数据通过无线电探空仪获取，每日2次（00:00和12:00 UTC），观测要素包括各规定气压层（1000hPa至1hPa）的气压、位势高度、温度、露点温度、风向风速等。本研究使用的数据来自国家气象信息中心发布的观测数据集，数据格式为TAB分隔的文本文件，每条记录包含区站号（5位数字编码）、观测时间、各气象要素值以及质量控制标识。")

H("2.1.3  多源数据融合策略",3)
P("多源气象数据融合是指将来自不同观测系统、不同时空分辨率的气象数据进行一致性处理和合并。本研究面临的融合挑战包括：（1）空间尺度差异——地面观测为站点级数据（18个台站覆盖北京各区），而天气网站数据为城市级数据；（2）时间分辨率差异——地面观测为3小时间隔，高空探空为12小时间隔，天气网站为每日数据；（3）字段命名和单位差异——不同数据源对同一要素使用不同的字段名称和计量单位。本系统通过建立统一的标准化数据模型（Weather Standard Schema）来解决上述问题，将所有来源的数据转换到统一的字段命名、时间粒度和计量单位体系。")

H("2.2  数据清洗与质控方法",2)
P("数据清洗（Data Cleaning）是数据分析和机器学习流程中不可或缺的环节，其质量直接影响后续建模的准确性和可靠性。气象观测数据由于仪器故障、传输错误、人为录入失误等原因，常含有各种数据质量问题。")

H("2.2.1  缺失值处理",3)
P("缺失值是气象数据中最常见的数据质量问题之一。缺失机制可分为三类：完全随机缺失（MCAR）、随机缺失（MAR）和非随机缺失（MNAR）。本研究采用自适应缺失值处理策略：首先对每个字段的缺失率进行评估，若缺失率小于5%，使用线性插值法填补；若缺失率在5%-20%之间，使用基于相邻站点或相邻时次的中位数填补；若缺失率大于20%，将该字段标记为不可靠并记录在质控报告中。对于系统性缺失（如某站点长期缺少某要素），系统会发出警告提示，建议从分析中排除该要素。")

H("2.2.2  异常值检测",3)
P("气象观测数据中常含有由仪器故障或记录错误导致的异常值。本研究采用四分位距（IQR）方法进行异常值检测：对于每个气象变量，计算其第一四分位数Q1和第三四分位数Q3，定义正常值范围为[Q1-1.5×IQR, Q3+1.5×IQR]，超出此范围的值被标记为疑似异常值。此外，系统还结合物理阈值范围进行双重校验——例如，北京地区夏季气温不可能超过50°C或低于-30°C，超出物理范围的值直接标记为错误。")

H("2.2.3  哨兵值识别与处理",3)
P("气象观测数据中使用特定的哨兵值（Sentinel Value）表示特殊状态。例如，CMA地面观测数据中，用999017表示风向数据缺失，用999990表示降水量缺测（微量降水或未观测），用999.x系列表示气压数据的各种异常情况。正确识别和处理哨兵值对于数据质量至关重要。本系统维护了一个哨兵值映射表，在数据加载阶段自动将哨兵值转换为NaN或保留原值（视物理含义而定），并进行相应的记录和报告。")

H("2.3  机器学习相关算法",2)
P("本研究采用多种机器学习算法构建气象-疾病的关联模型，通过系统对比筛选出最优模型。以下介绍本研究使用的核心算法。")

H("2.3.1  梯度提升决策树（GBDT）",3)
P("梯度提升决策树（Gradient Boosting Decision Tree, GBDT）是一种基于Boosting策略的集成学习算法。其核心思想是通过迭代训练一系列弱学习器（通常为CART决策树），每一轮新模型在前一轮模型残差（负梯度方向）上进行拟合，逐步减小整体模型的预测误差。GBDT的优势在于能够自动捕捉特征间的非线性关系和交互效应，对异常值和缺失值具有较强的鲁棒性[15]。本研究使用的LightGBM是微软提出的GBDT高效实现，采用基于直方图的决策树算法和单边梯度采样（GOSS）策略，相比传统GBDT实现训练速度可提升10倍以上，内存消耗降低至1/3，尤其适合处理大规模气象时序数据。XGBoost是陈天奇等人开发的另一高效GBDT实现，引入正则化项控制模型复杂度，有效防止过拟合。")

H("2.3.2  随机森林（Random Forest）",3)
P("随机森林是由Breiman提出的一种基于Bagging策略的集成学习算法，通过构建多棵决策树并对其预测结果进行平均（回归）或投票（分类）来降低方差、提高泛化能力。每棵决策树在训练时使用自助采样（Bootstrap）从原始数据中抽取训练子集，并在每个节点分裂时从随机选取的特征子集中选择最优分裂特征。这种双随机机制（样本随机+特征随机）使得随机森林具有良好的抗过拟合能力和对噪声数据的鲁棒性。随机森林还可以输出特征重要性排序，为解释气象因素对疾病风险的贡献提供依据[16]。")

H("2.3.3  线性回归及其正则化变体",3)
P("线性回归是最基础的回归模型，假设目标变量与特征之间存在线性关系。虽然其假设简单，但在许多实际应用中仍有价值，可作为评估更复杂模型效果的基线。Ridge回归（L2正则化）通过在损失函数中添加系数平方和惩罚项，防止系数过大；Lasso回归（L1正则化）使用系数绝对值之和作为惩罚项，具有产生稀疏解的特性，可自动实现特征选择；ElasticNet结合了L1和L2正则化，在特征高度相关时表现更佳。本研究同时纳入这些线性模型作为基准对照，以评估非线性模型相对于线性模型的性能提升幅度。")

H("2.3.4  支持向量回归（SVR）",3)
P("支持向量回归（Support Vector Regression）是支持向量机在回归问题上的扩展。SVR通过引入ε-不敏感损失函数，在特征空间中寻找一个最优超平面，使得大部分训练样本落在距离超平面±ε的管道内。通过核技巧（如RBF核），SVR可以隐式地将数据映射到高维空间，处理非线性回归问题。SVR在小样本、高维度数据上具有较好表现，但由于计算复杂度较高（O(n²)~O(n³)），在大规模数据上训练效率较低。本研究将其纳入对比，验证其在本数据集上的适用性。")

H("2.3.5  模型评估指标体系",3)
P("为全面评估各模型在气象-疾病关联预测中的表现，本研究采用以下七种评估指标的完整组合：")
P("（1）决定系数（R²）：衡量模型对目标变量方差的比例解释能力，取值范围(-∞, 1]，越接近1表示拟合效果越好。其数学定义为：R² = 1 - SS_res / SS_tot。")
P("（2）调整R²（Adjusted R²）：对R²的自由度修正，惩罚过多的特征数量，防止因特征增加导致的R²虚高。计算公式为：Adj R² = 1 - (1-R²)(n-1)/(n-p-1)。")
P("（3）平均绝对误差（MAE）：预测值与真实值绝对差的平均值，对异常值不敏感，单位与目标变量一致，便于业务人员理解。")
P("（4）均方误差（MSE）和均方根误差（RMSE）：MSE为预测误差平方的均值，RMSE为其平方根。RMSE对较大误差施加更高的惩罚权重（平方放大效应），是评估模型预测精度的重要指标。")
P("（5）平均绝对百分比误差（MAPE）：以百分比形式表示的预测误差，消除了量纲影响，便于不同尺度数据的模型间比较。")
P("（6）最大误差（Max Error）：预测误差绝对值的最大值，反映模型在最坏情况下的表现。")
P("（7）交叉验证R²均值和标准差：通过K折交叉验证评估模型在不同数据子集上的表现稳定性，均值衡量平均泛化能力，标准差衡量表现一致性。")

H("2.4  智能体技术概述",2)
P("智能体（Agent）是人工智能领域的核心概念，指能够通过传感器感知环境、通过执行器作用于环境、并自主决策以实现预设目标的软件或硬件实体。一个典型的智能体系统包含以下核心组件：（1）感知模块——从环境中采集和接收信息；（2）推理决策模块——基于当前状态和知识库做出规划和决策；（3）执行模块——将决策转化为具体行动；（4）记忆模块——存储历史记录和知识。")
P("本研究借鉴智能体架构的设计思想，将气候健康风险预警平台构建为一个配置驱动的多智能体系统。具体而言，系统定义了六类专用智能体：（1）CrawlAgent（数据采集智能体）——负责多源数据的自动调度和采集；（2）CleanAgent（数据清洗智能体）——执行自适应数据清洗和质控；（3）FeatureEngineer（特征工程智能体）——自动化特征构建和筛选；（4）ModelAgent（建模智能体）——多模型自适应训练和对比；（5）EvalAgent（评测智能体）——全维度模型性能评估；（6）ReportAgent（报告智能体）——自动生成分析报告和可视化图表。")
P("这些智能体通过AgentPipeline（智能体管线调度引擎）进行编排，按照Crawl → Clean → Feature → Model → Eval → Report的顺序依次执行，每步执行完毕后检查是否有异常（anomaly）产生；若有异常，系统自动暂停并等待人工复核，确保分析链条的可靠性和可追溯性。此外，平台还集成了基于大语言模型的AI助手智能体，通过自然语言对话界面为用户提供平台使用指导、数据分析辅助和模型结果解读。")

