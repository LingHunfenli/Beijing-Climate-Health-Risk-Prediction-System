add_heading("2.3.5  模型评估指标体系", level=3)
add_para(
    "为全面评估各模型在气象-疾病关联预测中的表现，本研究采用以下七种评估指标的完整组合："
)
add_para(
    "（1）决定系数（R²）：衡量模型对目标变量方差的比例解释能力，取值范围(-∞, 1]，"
    "越接近1表示拟合效果越好。其数学定义为：R² = 1 - SS_res / SS_tot，其中SS_res为"
    "残差平方和，SS_tot为总平方和。"
)
add_para(
    "（2）调整R²（Adjusted R²）：对R²的自由度修正，惩罚过多的特征数量，防止因特征增加"
    "导致的R²虚高。计算公式为：Adj R² = 1 - (1-R²)(n-1)/(n-p-1)，其中n为样本数，p为特征数。"
)
add_para(
    "（3）平均绝对误差（MAE）：预测值与真实值绝对差的平均值，对异常值不敏感，单位与目标"
    "变量一致，便于业务人员理解。"
)
add_para(
    "（4）均方误差（MSE）和均方根误差（RMSE）：MSE为预测误差平方的均值，RMSE为其平方根。"
    "RMSE对较大误差施加更高的惩罚权重（平方放大效应），是评估模型预测精度的重要指标。"
)
add_para(
    "（5）平均绝对百分比误差（MAPE）：以百分比形式表示的预测误差，消除了量纲影响，便于"
    "不同尺度数据的模型间比较。"
)
add_para(
    "（6）最大误差（Max Error）：预测误差绝对值的最大值，反映模型在最坏情况下的表现，"
    "对于风险预警等安全性敏感的应用至关重要。"
)
add_para(
    "（7）交叉验证R²均值和标准差：通过K折交叉验证评估模型在不同数据子集上的表现稳定性，"
    "均值衡量平均泛化能力，标准差衡量表现一致性。标准差越小，模型对不同数据子集的适应"
    "能力越稳定。"
)

